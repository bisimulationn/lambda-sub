Inductive StarN (R : ntrm -> ntrm -> Prop) : ntrm -> ntrm -> Prop :=
| starN_refl : forall t, StarN R t t
| starN_step : forall t u v, R t u -> StarN R u v -> StarN R t v.

Inductive PlusN (R : ntrm -> ntrm -> Prop) : ntrm -> ntrm -> Prop :=
| plusN1 : forall t u, R t u -> PlusN R t u
| plusNS : forall t u v, R t u -> PlusN R u v -> PlusN R t v.

Lemma StarN_trans : forall R a b c, StarN R a b -> StarN R b c -> StarN R a c.
Proof.
  intros R a b c H. induction H; intros Hbc.
  - exact Hbc.
  - apply starN_step with (u := u). exact H. apply IHStarN. exact Hbc.
Qed.

Lemma StarN_one_trans : forall R a b c, R a b -> StarN R b c -> StarN R a c.
Proof. intros. apply starN_step with (u := b); assumption. Qed.

Lemma PlusN_to_StarN : forall R t u, PlusN R t u -> StarN R t u.
Proof.
  intros R t u H. induction H.
  - apply starN_step with (u := u); [exact H | apply starN_refl].
  - apply starN_step with (u := u); [exact H | exact IHPlusN].
Qed.

Lemma StarN_subred_context : forall C t t',
    StarN subred t t' -> StarN subred (nplug C t) (nplug C t').
Proof.
  intros C t t' H. induction H.
  - apply starN_refl.
  - apply starN_step with (u := nplug C u).
    + apply subred_context. exact H.
    + exact IHStarN.
Qed.

